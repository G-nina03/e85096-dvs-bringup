#!/bin/sh
# Program the LT8912B MIPI-DSI -> HDMI bridge of the E850-96 for 1920x1080@60 (4 lanes).
#
# Run it once DSIM0 is streaming video (after `modprobe dpu`). The register values are the
# ones of the mainline driver drivers/gpu/drm/bridge/lontium-lt8912b.c (Linux v6.6):
#   attach: init_config, lanes, mipi_basic   enable: video_setup, dds, rxlogicres, lvds
# with the CEA-861 1080p60 timing used by the E850-96 Android 10 DT:
#   H 1920 + fp 88 + sync 44 + bp 148 = 2200, V 1080 + fp 4 + sync 5 + bp 36 = 1125
#
#   lt8912b-hdmi.sh          program the bridge
#   lt8912b-hdmi.sh status   chip ID and HPD (cable) state only
set -e

# i2c bus of i2c@13840000 (i2c_1), whatever number Linux gave it
BUS=
for d in /sys/bus/i2c/devices/i2c-*; do
    case "$(readlink -f $d/of_node 2>/dev/null)" in *i2c@13840000) BUS=${d##*-} ;; esac
done
[ -n "$BUS" ] || { echo "i2c@13840000 not found (is i2c_1 enabled in the DT?)" >&2; exit 1; }

MAIN=0x48   # main page
DSI=0x49    # CEC/DSI page

w() { i2cset -y -f $BUS $1 $2 $3; }
r() { i2cget -y -f $BUS $1 $2; }

echo "LT8912B on i2c-$BUS: chip id regs 0x00,0x01 = $(r $MAIN 0x00) $(r $MAIN 0x01)"
if [ "$1" = status ]; then
    hpd=$(( $(r $MAIN 0xc1) & 0x80 ))
    [ $hpd -ne 0 ] && echo "HDMI cable: connected" || echo "HDMI cable: not connected"
    exit 0
fi

regs() { page=$1; shift; while [ $# -ge 2 ]; do w $page $1 $2; shift 2; done; }

# lt8912_write_init_config: digital clocks, TX/CBUS/HDMI PLL/MIPI analog
regs $MAIN 0x08 0xff 0x09 0xff 0x0a 0xff 0x0b 0x7c 0x0c 0xff 0x42 0x04 \
          0x31 0xb1 0x32 0xb1 0x33 0x0e 0x37 0x00 0x38 0x22 0x60 0x82 \
          0x39 0x45 0x3a 0x00 0x3b 0x00 \
          0x44 0x31 0x55 0x44 0x57 0x01 0x5a 0x02 \
          0x3e 0xd6 0x3f 0xd4 0x41 0x3c 0xb2 0x00
# 4 data lanes: 0x13 = lanes & 3 = 0
w $DSI 0x13 0x00
# lt8912_write_mipi_basic_config
regs $DSI 0x12 0x04 0x14 0x00 0x15 0x00 0x1a 0x03 0x1b 0x03

# lt8912_video_setup: 1080p60, settle 0x0a for 1080 lines
regs $DSI 0x10 0x01 0x11 0x0a \
         0x18 0x2c 0x19 0x05 \
         0x1c 0x80 0x1d 0x07 \
         0x2f 0x0c \
         0x34 0x98 0x35 0x08 \
         0x36 0x65 0x37 0x04 \
         0x38 0x24 0x39 0x00 \
         0x3a 0x04 0x3b 0x00 \
         0x3c 0x94 0x3d 0x00 \
         0x3e 0x58 0x3f 0x00
# sync polarity: both positive for CEA 1080p (0xab bit0 vsync, bit1 hsync); 0xb2 bit0 = HDMI mode
w $MAIN 0xab $(( $(r $MAIN 0xab) | 0x03 ))
w $MAIN 0xb2 $(( $(r $MAIN 0xb2) | 0x01 ))

# lt8912_write_dds_config
regs $DSI 0x4e 0xff 0x4f 0x56 0x50 0x69 0x51 0x80 0x1f 0x5e 0x20 0x01 0x21 0x2c 0x22 0x01 \
         0x23 0xfa 0x24 0x00 0x25 0xc8 0x26 0x00 0x27 0x5e 0x28 0x01 0x29 0x2c 0x2a 0x01 \
         0x2b 0xfa 0x2c 0x00 0x2d 0xc8 0x2e 0x00 0x42 0x64 0x43 0x00 0x44 0x04 0x45 0x00 \
         0x46 0x59 0x47 0x00 0x48 0xf2 0x49 0x06 0x4a 0x00 0x4b 0x72 0x4c 0x45 0x4d 0x00 \
         0x52 0x08 0x53 0x00 0x54 0xb2 0x55 0x00 0x56 0xe4 0x57 0x0d 0x58 0x00 0x59 0xe4 \
         0x5a 0x8a 0x5b 0x00 0x5c 0x34 0x1e 0x4f 0x51 0x00

# lt8912_write_rxlogicres_config: MIPI RX logic reset
w $MAIN 0x03 0x7f
sleep 0.02
w $MAIN 0x03 0xff

# lt8912_write_lvds_config (mainline always does it; it also sets up the core PLL)
regs $MAIN 0x44 0x30 0x51 0x05 0x50 0x24 0x51 0x2d 0x52 0x04 0x69 0x0e 0x69 0x8e 0x6a 0x00 \
          0x6c 0xb8 0x6b 0x51 0x04 0xfb 0x04 0xff 0x7f 0x00 0xa8 0x13 \
          0x02 0xf7 0x02 0xff 0x03 0xcf 0x03 0xff

hpd=$(( $(r $MAIN 0xc1) & 0x80 ))
echo "LT8912B programmed for 1920x1080@60; HDMI cable: $([ $hpd -ne 0 ] && echo connected || echo 'not connected')"
